ucd_property ucd_properties(codepoint_t c, ucd_category category) {
    uint32_t cat=(uint32_t)category;
    if(cat>=sizeof defaults/sizeof *defaults) return 0;
    if(c>0x10ffff) {
        /* Upstream Cn applies this low-16-bit rule even outside Unicode. */
        if(category==UCD_CATEGORY_Cn && (c&0xffff)>=0xfffe) return UCD_PROPERTY_NONCHARACTER_CODE_POINT;
        return values[defaults[cat]];
    }
    uint32_t key=(cat<<21)|c;
    size_t lo=0,hi=sizeof first/sizeof *first;
    while(lo<hi) { size_t mid=lo+(hi-lo)/2; if(first[mid]<=key) lo=mid+1; else hi=mid; }
    if(lo && key-first[lo-1]<=span[lo-1]) return values[value_id[lo-1]];
    return values[defaults[cat]];
}
