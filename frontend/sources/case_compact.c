static codepoint_t lookup(const CaseRange *table, size_t count, codepoint_t c, codepoint_t fallback) {
    size_t lo=0, hi=count;
    while(lo<hi) {
        size_t mid=lo+(hi-lo)/2;
        if(table[mid].first<=c) lo=mid+1; else hi=mid;
    }
    if(!lo) return fallback;
    const CaseRange *r=table+lo-1;
    if(c>r->last || (r->stride==2 && ((c-r->first)&1))) return fallback;
    /* The generated target is in range; unsigned arithmetic is defined. */
    return c+(uint32_t)r->delta;
}
