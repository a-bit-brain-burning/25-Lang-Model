"""Build a guarded eSpeak text-to-phoneme variant; never edits upstream.

All phondata payload readers are replaced with fail-fast guards. Public audio
synthesis returns ENS_NOT_SUPPORTED, so an accidental audio call cannot read
past the retained eight-byte header or silently synthesize a different voice.
"""
import argparse
import concurrent.futures
import difflib
import hashlib
import json
import re
import subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parent
WORK = HERE.parent
AUDIT = WORK / 'm4_frontend_rom_accounting_20261023'
SOURCE = WORK / 'm4_frontend_4mb_20261022/upstream/espeak-ng'
BIN = AUDIT / 'toolchain/usr/bin'
LIB = AUDIT / 'toolchain/usr/lib/arm-none-eabi/newlib/thumb/v7e-m+fp/hard'
FLAGS = ['-mcpu=cortex-m4', '-mthumb', '-mfpu=fpv4-sp-d16', '-mfloat-abi=hard', '-Os',
         '-ffunction-sections', '-fdata-sections', '-fno-unwind-tables', '-fno-asynchronous-unwind-tables',
         '-fno-use-linker-plugin', '-isystem', str(AUDIT / 'toolchain/usr/include/newlib'), '-B', str(BIN) + '/']
EXPORTS = ['espeak_Initialize', 'espeak_Info', 'espeak_SetVoiceByName', 'espeak_GetCurrentVoice',
           'espeak_TextToPhonemes', 'espeak_Terminate', 'espeak_Synth']


def sha(data):
    return hashlib.sha256(data).hexdigest()


def replace_body(source, name, body):
    # Fixed upstream revision uses column-zero function braces. Assert unique.
    pattern = re.compile(r'\b' + re.escape(name) + r'\([^;{}]*\)\s*\n\{', re.S)
    matches = list(pattern.finditer(source))
    assert len(matches) == 1, (name, len(matches))
    start = matches[0].end()
    end = source.index('\n}', start)
    return source[:start] + '\n' + body + source[end:]


def prepare():
    assert subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=SOURCE, text=True).strip() == '4870adfa25b1a32b4361592f1be8a40337c58d6c'
    directory = HERE / 'patched'
    directory.mkdir(exist_ok=True)
    records, patch = [], []
    for name in ('synthdata', 'synthesize', 'speech'):
        original = (SOURCE / 'src/libespeak-ng' / (name + '.c')).read_text()
        text = original
        if name == 'synthdata':
            for function in ('LookupSpect', 'GetEnvelope'):
                text = replace_body(text, function, '\t/* Text-to-phoneme-only build: no waveform payload exists. */\n\tabort();')
            old = 'ReadPhFile((void **)&phondata_ptr, "phondata", NULL, context)'
            assert text.count(old) == 1
            text = text.replace(old, 'ReadPhFile((void **)&phondata_ptr, "phondata", &length, context)')
            anchor = '\tif ((status = ReadPhFile((void **)&tunes, "intonations", &length, context))'
            assert text.count(anchor) == 1
            text = text.replace(anchor, '\t/* Require the matching header-only resource; reject mismatched packs. */\n\tif (length != 8)\n\t\treturn ENS_NOT_SUPPORTED;\n' + anchor)
            assert 'phondata_ptr[' not in text
        elif name == 'synthesize':
            text = replace_body(text, 'DoSample2', '\t/* No sample-bank access is permitted by this build. */\n\tabort();')
            assert 'wavefile_data[' not in text
        else:
            for function in ('espeak_ng_Synthesize', 'espeak_ng_SynthesizeMark'):
                text = replace_body(text, function, '\t/* Audio is generated by the project acoustic model and DSP. */\n\treturn ENS_NOT_SUPPORTED;')
        (directory / (name + '.c')).write_text(text)
        records.append({'file': name + '.c', 'upstream_sha256': sha(original.encode()), 'patched_sha256': sha(text.encode())})
        patch.extend(difflib.unified_diff(original.splitlines(True), text.splitlines(True),
                                        fromfile='a/src/libespeak-ng/' + name + '.c', tofile='b/src/libespeak-ng/' + name + '.c'))
    (HERE / 'phoneme_only.patch').write_text(''.join(patch))
    (HERE / 'SOURCE_PATCH.json').write_text(json.dumps({'upstream_commit': '4870adfa25b1a32b4361592f1be8a40337c58d6c',
        'files': records, 'retained_header_bytes': 8, 'payload_readers_guarded': ['LookupSpect', 'GetEnvelope', 'DoSample2'],
        'public_audio_synthesis': 'explicitly unsupported', 'phoneme_rule_tables_and_interpreter': 'unchanged'}, indent=2) + '\n')
    return directory


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--sanitize', action='store_true')
    args = parser.parse_args()
    patched = prepare()
    jobs = json.loads((AUDIT / 'ARM_OBJECTS.json').read_text())
    directory = HERE / ('sanitize_build' if args.sanitize else 'host_build')
    directory.mkdir(exist_ok=True)
    includes = [AUDIT / 'arm_build', SOURCE / 'src/libespeak-ng', SOURCE / 'src/include',
                SOURCE / 'src/include/compat', SOURCE / 'src/ucd-tools/src/include']
    definitions = ['-DLIBESPEAK_NG_EXPORT=1', '-DPATH_ESPEAK_DATA="/espeak-ng-data"']
    sanitized = ['-fsanitize=address,undefined', '-fno-omit-frame-pointer', '-g'] if args.sanitize else []
    commands = []

    def run(command, log):
        command = list(map(str, command))
        commands.append(command)
        result = subprocess.run(command, capture_output=True, text=True)
        log.write_text(result.stdout + result.stderr)
        if result.returncode:
            raise RuntimeError(str(log))

    def compile_one(row):
        source = Path(row['source'])
        if (patched / source.name).exists() and row['group'] == 'espeak':
            source = patched / source.name
        obj = directory / Path(row['object']).name
        run(['gcc', '-Os', '-fPIC', '-fvisibility=hidden', '-fwrapv', '-ffunction-sections', '-fdata-sections',
             *sanitized, *definitions, *[v for p in includes for v in ('-I', p)], '-c', source, '-o', obj], obj.with_suffix('.log'))
        return obj

    selected = [r for r in jobs if r['group'] in ('espeak', 'ucd')]
    with concurrent.futures.ThreadPoolExecutor(max_workers=3) as pool:
        objects = list(pool.map(compile_one, selected))
    exports = HERE / 'exports.map'
    exports.write_text('{ global: ' + '; '.join(EXPORTS) + '; local: *; };\n')
    run(['gcc', '-shared', *sanitized, '-Wl,--gc-sections', '-Wl,--version-script=' + str(exports),
         *objects, '-lm', '-o', directory / 'libespeak_phonemes.so'], directory / 'link.log')
    if not args.sanitize:
        arm = HERE / 'arm_build'
        arm.mkdir(exist_ok=True)
        arm_objects = []
        for row in jobs:
            source = Path(row['source'])
            obj = Path(row['object'])
            if row['group'] == 'espeak' and (patched / source.name).exists():
                obj = arm / obj.name
                run([BIN / 'arm-none-eabi-gcc', *FLAGS, *definitions,
                     *[v for p in [AUDIT / 'compat', *includes] for v in ('-I', p)],
                     '-D_DEFAULT_SOURCE', '-D_POSIX_C_SOURCE=200809L', '-c', patched / source.name, '-o', obj], obj.with_suffix('.log'))
            arm_objects.append(obj)
        manifest = json.loads((HERE / 'CANDIDATE_MANIFEST.json').read_text())
        assembly = ['.section .frontend_assets,"a",%progbits']
        for i, row in enumerate(manifest['files']):
            assembly += ['.balign 4', f'.global frontend_asset_{i}', f'frontend_asset_{i}:',
                         '.incbin "' + str(HERE / 'packages' / row['file']) + '"']
        (arm / 'assets.S').write_text('\n'.join(assembly) + '\n')
        run([BIN / 'arm-none-eabi-gcc', *FLAGS, '-c', arm / 'assets.S', '-o', arm / 'assets.o'], arm / 'assets.log')
        roots = ['fep_read', 'fep_keys', 'fep_id', 'fep_pool', 'spr_open', 'spr_predict', 'spr_apply',
                 'en_apply', 'phrase_apply', 'primary_id', 'aux_expand', 'open_predict', 'open_word_allowed',
                 'lex_open', 'lex_section', 'lex_unpack', 'lex_lookup', *EXPORTS]
        for name, asset in [('code', []), ('with_assets', [arm / 'assets.o'])]:
            run([BIN / 'arm-none-eabi-gcc', *FLAGS, '-nostartfiles', '-L', LIB, '--specs=' + str(LIB / 'nosys.specs'),
                 '-T', AUDIT / 'size_probe.ld', '-Wl,--gc-sections', '-Wl,-Map=' + str(arm / (name + '.map')),
                 *['-Wl,-u,' + s for s in roots], *arm_objects, *asset,
                 AUDIT / 'arm_build/xz/src/liblzma/.libs/liblzma.a', '-Wl,--start-group', '-lc_nano', '-lm', '-lgcc',
                 '-lnosys', '-Wl,--end-group', '-o', arm / (name + '.elf')], arm / (name + '_link.log'))
            run([BIN / 'arm-none-eabi-objcopy', '-O', 'binary', arm / (name + '.elf'), arm / (name + '.bin')], arm / (name + '_objcopy.log'))
            print(name, (arm / (name + '.bin')).stat().st_size, flush=True)
    (directory / 'BUILD_COMMANDS.json').write_text(json.dumps(commands, indent=2) + '\n')


if __name__ == '__main__':
    main()
